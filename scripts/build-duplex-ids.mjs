#!/usr/bin/env node
/**
 * List the helpmates YACPDB marks as Duplex, from the raw cache.
 *
 * YACPDB records "Duplex" in the entry's `options` field — the same place as
 * SetPlay and fairy conditions, i.e. it is part of the stipulation, not a
 * theme. Only about half of those entries also carry the "Duplex" keyword,
 * and the problems table stores keywords only, so the app cannot tell a
 * duplex from the database alone. This writes the ids to src/data/duplexIds.ts.
 *
 * Only integer h#N problems are listed (that is what the help genre holds;
 * h#N.5, h= and direct-mate duplexes are not in the database).
 *
 * Re-run after a YACPDB import (the cache is refreshed by the update script).
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CACHE = resolve(ROOT, 'scripts/.cache');
const OUT = resolve(ROOT, 'src/data/duplexIds.ts');

const ids = [];
for (const f of readdirSync(CACHE)) {
  if (!f.endsWith('.json')) continue;
  let d;
  try { d = JSON.parse(readFileSync(resolve(CACHE, f), 'utf8')); } catch { continue; }
  if (!d || typeof d.id !== 'number' || typeof d.stipulation !== 'string') continue;
  if (!/^h#\d+$/.test(d.stipulation)) continue;
  if (!Array.isArray(d.options) || !d.options.includes('Duplex')) continue;
  ids.push(d.id);
}
ids.sort((a, b) => a - b);

const lines = [];
for (let i = 0; i < ids.length; i += 16) lines.push('  ' + ids.slice(i, i + 16).join(', ') + ',');
writeFileSync(OUT,
  `// Generated by scripts/build-duplex-ids.mjs — do not edit by hand.\n` +
  `// Helpmates whose YACPDB entry carries the "Duplex" option: the diagram is\n` +
  `// solved twice, once with Black to play and once with White to play (Black\n` +
  `// and White mate the white king). ${ids.length} problems.\n` +
  `export const DUPLEX_IDS: ReadonlySet<number> = new Set([\n${lines.join('\n')}\n]);\n`);
console.log(`${ids.length} duplex helpmates → ${OUT.replace(ROOT + '/', '')}`);
